// The frontend's copy of CONTRACT-MENTORSHIP-API (ADR-012). The typed client is generated from openapi/mentor-api.json at
// build time; this script keeps that copy honest.
//
//   node scripts/openapi.mjs fetch [baseUrl]  replaces the copy with the document a running API serves
//   node scripts/openapi.mjs check [baseUrl]  fails when the running API's document differs from the copy (drift)
//   node scripts/openapi.mjs enums            writes src/api/enums.gen.ts: every enumeration's values, from the copy
//
// baseUrl defaults to MENTOR_API_URL, then http://localhost:5080. The API serves its document only with OpenApi:Enabled
// (Development), and lists the simulated-identity roster route only under Identity:Mode=Simulated, so the copy is taken
// from an API run in that mode.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const web = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const copy = resolve(web, "openapi/mentor-api.json");
const enums = resolve(web, "src/api/enums.gen.ts");

const [mode, baseUrl = process.env.MENTOR_API_URL ?? "http://localhost:5080"] = process.argv.slice(2);

function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.keys(value).sort().map((key) => [key, canonical(value[key])]));
  }
  return value;
}

const serialise = (document) => `${JSON.stringify(document, null, 2)}\n`;

async function live() {
  const url = new URL("/openapi/v1.json", baseUrl);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`GET ${url} answered ${response.status}`);
  return response.json();
}

async function stored() {
  return JSON.parse(await readFile(copy, "utf8"));
}

switch (mode) {
  case "fetch": {
    await writeFile(copy, serialise(await live()));
    console.log(`Wrote ${copy} from ${baseUrl}`);
    break;
  }
  case "check": {
    const [served, kept] = await Promise.all([live(), stored()]);
    if (JSON.stringify(canonical(served)) !== JSON.stringify(canonical(kept))) {
      console.error(`The API at ${baseUrl} serves a contract that differs from openapi/mentor-api.json; run "npm run openapi:fetch" and rebuild.`);
      process.exit(1);
    }
    console.log(`openapi/mentor-api.json matches the contract the API at ${baseUrl} serves.`);
    break;
  }
  case "enums": {
    const schemas = (await stored()).components?.schemas ?? {};
    const lines = Object.entries(schemas)
      .filter(([, schema]) => Array.isArray(schema.enum))
      .map(([name, schema]) => `  ${name}: ${JSON.stringify(schema.enum.filter((value) => value !== null))},`);
    await writeFile(
      enums,
      [
        "// Generated by scripts/openapi.mjs from openapi/mentor-api.json. Do not edit.",
        "// Every enumeration of CONTRACT-MENTORSHIP-API with its values, null aside: the browser offers what the contract names",
        "// and invents none (ADR-012).",
        "export const contractEnums = {",
        ...lines,
        "} as const;",
        "",
      ].join("\n"),
    );
    break;
  }
  default:
    console.error("usage: node scripts/openapi.mjs fetch|check|enums [baseUrl]");
    process.exit(64);
}
